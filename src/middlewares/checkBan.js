const {

  loadUsers

} = require(
  '../data/userData'
)

/*
|--------------------------------------------------------------------------
| CHECK BAN
|--------------------------------------------------------------------------
*/

const checkBan = async (
  ctx,
  next
) => {

  /*
  |--------------------------------------------------------------------------
  | NO USER
  |--------------------------------------------------------------------------
  */

  if (!ctx.from) {

    return next()

  }

  /*
  |--------------------------------------------------------------------------
  | USERS
  |--------------------------------------------------------------------------
  */

  const users =
    loadUsers()

  /*
  |--------------------------------------------------------------------------
  | FIND USER
  |--------------------------------------------------------------------------
  */

  const user =
    users.find(

      (u) =>

        u.id ===
        ctx.from.id

    )

  /*
  |--------------------------------------------------------------------------
  | USER BANNED
  |--------------------------------------------------------------------------
  */

  if (

    user &&

    user.banned

  ) {

    return ctx.reply(
`
🚫 Vous êtes banni.
`
    )

  }

  /*
  |--------------------------------------------------------------------------
  | NEXT
  |--------------------------------------------------------------------------
  */

  return next()

}

/*
|--------------------------------------------------------------------------
| ANTI SPAM
|--------------------------------------------------------------------------
*/

const spamMap =
new Map()

const antiSpam =
async (
  ctx,
  next
) => {

  /*
  |--------------------------------------------------------------------------
  | NO USER
  |--------------------------------------------------------------------------
  */

  if (!ctx.from) {

    return next()

  }

  const userId =
    ctx.from.id

  const now =
    Date.now()

  const lastMessage =
    spamMap.get(userId) || 0

  /*
  |--------------------------------------------------------------------------
  | SPAM LIMIT
  |--------------------------------------------------------------------------
  */

  if (
    now - lastMessage < 800
  ) {

    return

  }

  /*
  |--------------------------------------------------------------------------
  | SAVE
  |--------------------------------------------------------------------------
  */

  spamMap.set(
    userId,
    now
  )

  /*
  |--------------------------------------------------------------------------
  | NEXT
  |--------------------------------------------------------------------------
  */

  return next()

}

module.exports = {

  checkBan,

  antiSpam

}