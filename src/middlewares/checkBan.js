const User =
require(
  '../models/User'
)

/*
|--------------------------------------------------------------------------
| CHECK BAN
|--------------------------------------------------------------------------
*/

const checkBan =
async (

  ctx,

  next

) => {

  if (!ctx.from) {

    return next()

  }

  const user =
    await User.findOne({

      id: ctx.from.id

    })

  /*
  |--------------------------------------------------------------------------
  | BANNED
  |--------------------------------------------------------------------------
  */

  if (user?.banned) {

    return ctx.reply(
`
🚫 Vous êtes banni.
`
    )

  }

  /*
  |--------------------------------------------------------------------------
  | MUTED
  |--------------------------------------------------------------------------
  */

  if (user?.muted) {

    return

  }

  return next()

}

