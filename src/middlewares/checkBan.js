const {

  getUser

} = require(
  '../services/userService'
)

/*
|--------------------------------------------------------------------------
| CHECK BAN
|--------------------------------------------------------------------------
*/

const checkBan =
async (
  ctx,
  next
) => {

  /*
  |--------------------------------------------------------------------------
  | NO USER
  |--------------------------------------------------------------------------
  */

  if (!ctx.from) {

    return next()

  }

  /*
  |--------------------------------------------------------------------------
  | GET USER
  |--------------------------------------------------------------------------
  */

  const user =
    await getUser(
      ctx.from.id
    )

  /*
  |--------------------------------------------------------------------------
  | BANNED
  |--------------------------------------------------------------------------
  */

  if (

    user &&

    user.banned

  ) {

    return ctx.reply(
`
🚫 Vous êtes banni.
`
    )

  }

  /*
  |--------------------------------------------------------------------------
  | NEXT
  |--------------------------------------------------------------------------
  */

  return next()

}

/*
|--------------------------------------------------------------------------
| ANTI SPAM
|--------------------------------------------------------------------------
*/

const spamMap =
new Map()

const antiSpam =
async (
  ctx,
  next
) => {

  if (!ctx.from) {

    return next()

  }

  const userId =
    ctx.from.id

  const now =
    Date.now()

  const lastMessage =
    spamMap.get(userId) || 0

  /*
  |--------------------------------------------------------------------------
  | LIMIT
  |--------------------------------------------------------------------------
  */

  if (
    now - lastMessage < 800
  ) {

    return

  }

  spamMap.set(

    userId,

    now

  )

  return next()

}

