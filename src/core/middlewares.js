const {

  session

} = require('telegraf')

const {

  checkBan,

  antiSpam

} = require(
  '../middlewares/checkBan'
)

const antiSpamMiddleware =
require(
  '../middlewares/antiSpam'
)

const {

  registerUser

} = require(
  '../handlers/userHandler'
)

/*
|--------------------------------------------------------------------------
| REGISTER MIDDLEWARES
|--------------------------------------------------------------------------
*/

const registerMiddlewares =
(bot) => {

  /*
  |--------------------------------------------------------------------------
  | SESSION
  |--------------------------------------------------------------------------
  */

  bot.use(
    session()
  )

  /*
  |--------------------------------------------------------------------------
  | SECURITY
  |--------------------------------------------------------------------------
  */

  bot.use(
    checkBan
  )

  /*
  |--------------------------------------------------------------------------
  | ANTISPAM
  |--------------------------------------------------------------------------
  */

  bot.use(
    antiSpamMiddleware
  )

  /*
  |--------------------------------------------------------------------------
  | LEGACY ANTISPAM
  |--------------------------------------------------------------------------
  */

  bot.use(
    antiSpam
  )

  /*
  |--------------------------------------------------------------------------
  | USER ACTIVITY
  |--------------------------------------------------------------------------
  */

  bot.use(

    async (
      ctx,
      next
    ) => {

      if (ctx.from) {

        await registerUser(
          ctx
        )

      }

      return next()

    }

  )

}

module.exports =
registerMiddlewares