const express =
require('express')

const logger =
require(
  '../utils/logger'
)

const env =
require(
  '../config/env'
)

/*
|--------------------------------------------------------------------------
| EXPRESS
|--------------------------------------------------------------------------
*/

const app =
express()

/*
|--------------------------------------------------------------------------
| LAUNCH BOT
|--------------------------------------------------------------------------
*/

const launchBot =
async (bot) => {

  try {

    /*
    |--------------------------------------------------------------------------
    | WEBHOOK
    |--------------------------------------------------------------------------
    */

    const webhookUrl =
`${env.webhookUrl}/bot`

    await bot.telegram.setWebhook(
      webhookUrl
    )

    /*
    |--------------------------------------------------------------------------
    | WEBHOOK CALLBACK
    |--------------------------------------------------------------------------
    */

    app.use(
      bot.webhookCallback('/bot')
    )

    /*
    |--------------------------------------------------------------------------
    | ROOT
    |--------------------------------------------------------------------------
    */

    app.get(

      '/',

      (
        req,
        res
      ) => {

        res.send(
          'HACKWORLD BOT ONLINE'
        )

      }

    )

    /*
    |--------------------------------------------------------------------------
    | SERVER
    |--------------------------------------------------------------------------
    */

    const PORT =
      process.env.PORT || 3000

    app.listen(

      PORT,

      () => {

        logger(
`
🚀 Bot lancé en webhook
🌐 Port : ${PORT}
`
        )

      }

    )

  }

  catch (error) {

    console.log(error)

  }

}

module.exports =
launchBot