const logger =
require(
  '../utils/logger'
)

const env =
require(
  '../config/env'
)

/*
|--------------------------------------------------------------------------
| LAUNCH BOT
|--------------------------------------------------------------------------
*/

const launchBot =
async (bot) => {

  try {

    /*
    |--------------------------------------------------------------------------
    | WEBHOOK
    |--------------------------------------------------------------------------
    */

    await bot.telegram.setWebhook(

      `${env.webhookUrl}/bot`

    )

    /*
    |--------------------------------------------------------------------------
    | START WEBHOOK
    |--------------------------------------------------------------------------
    */

    bot.startWebhook(

      '/bot',

      null,

      process.env.PORT || 3000

    )

    /*
    |--------------------------------------------------------------------------
    | LOG
    |--------------------------------------------------------------------------
    */

    logger(
      '🚀 Bot lancé en webhook'
    )

  }

  catch (error) {

    console.log(error)

  }

}

module.exports =
launchBot