const {

  addContent

} = require(
  '../services/contentService'
)

const {

  replySuccess,

  replyError

} = require(
  '../utils/responses'
)

/*
|--------------------------------------------------------------------------
| OPEN ADD CONTENT
|--------------------------------------------------------------------------
*/

const openAddContent =
async (ctx) => {

  /*
  |--------------------------------------------------------------------------
  | SESSION
  |--------------------------------------------------------------------------
  */

  if (!ctx.session) {

    ctx.session = {}

  }

  /*
  |--------------------------------------------------------------------------
  | STEP
  |--------------------------------------------------------------------------
  */

  ctx.session.step =
    'add_content'

  /*
  |--------------------------------------------------------------------------
  | MESSAGE
  |--------------------------------------------------------------------------
  */

  await ctx.reply(
`
📦 ENVOI DU CONTENU

━━━━━━━━━━━━━━━━━━

📝 Envoyez maintenant le contenu.
`
  )

}

/*
|--------------------------------------------------------------------------
| HANDLE CONTENT
|--------------------------------------------------------------------------
*/

const handleAddContent =
async (ctx) => {

  /*
  |--------------------------------------------------------------------------
  | CHECK STEP
  |--------------------------------------------------------------------------
  */

  if (

    ctx.session.step !==
    'add_content'

  ) {

    return

  }

  /*
  |--------------------------------------------------------------------------
  | RESET
  |--------------------------------------------------------------------------
  */

  ctx.session.step =
    null

  /*
  |--------------------------------------------------------------------------
  | TEXT
  |--------------------------------------------------------------------------
  */

  const text =
    ctx.message.text

  if (!text) {

    return replyError(

      ctx,

      'Contenu invalide'

    )

  }

  /*
  |--------------------------------------------------------------------------
  | SAVE
  |--------------------------------------------------------------------------
  */

  addContent({

    text,

    author:
      ctx.from.username ||

      ctx.from.first_name,

    createdAt:
      new Date().toISOString()

  })

  /*
  |--------------------------------------------------------------------------
  | SUCCESS
  |--------------------------------------------------------------------------
  */

  return replySuccess(

    ctx,

    'Contenu ajouté avec succès'

  )

}

module.exports = {

  openAddContent,

  handleAddContent

}