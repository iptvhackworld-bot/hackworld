async (ctx) => {

  if (

    !ctx.from ||

    !ctx.from.id

  ) {

    return

  }

  let user =
    await getUserById(
      ctx.from.id
    )

  if (!user) {

    await createUser({

      id: ctx.from.id,

      username:
      ctx.from.username,

      firstName:
      ctx.from.first_name

    })

  }

}

/*
|--------------------------------------------------------------------------
| CHECK USER
|--------------------------------------------------------------------------
*/

const checkUser =
async (

  ctx,

  next

) => {

  /*
  |--------------------------------------------------------------------------
  | USER ID
  |--------------------------------------------------------------------------
  */

  const userId =
    getUserId(ctx)

  /*
  |--------------------------------------------------------------------------
  | INVALID
  |--------------------------------------------------------------------------
  */

  if (!userId) {

    return replyError(

      ctx,

      'Utilisateur invalide'

    )

  }

  /*
  |--------------------------------------------------------------------------
  | REGISTER
  |--------------------------------------------------------------------------
  */

  await registerUser(
    ctx
  )

  /*
  |--------------------------------------------------------------------------
  | NEXT
  |--------------------------------------------------------------------------
  */

  return next()

}

module.exports = {

  registerUser,

  checkUser

}