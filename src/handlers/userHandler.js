const {

  createUser,

  getUser

} = require(
  '../services/userService'
)

const {

  getUserId

} = require(
  '../utils/context'
)

const {

  replyError

} = require(
  '../utils/responses'
)

/*
|--------------------------------------------------------------------------
| REGISTER USER
|--------------------------------------------------------------------------
*/

const registerUser =
async (ctx) => {

  /*
  |--------------------------------------------------------------------------
  | USER ID
  |--------------------------------------------------------------------------
  */

  const userId =
    getUserId(ctx)

  /*
  |--------------------------------------------------------------------------
  | INVALID
  |--------------------------------------------------------------------------
  */

  if (!userId) {

    return null

  }

  /*
  |--------------------------------------------------------------------------
  | EXISTS
  |--------------------------------------------------------------------------
  */

  let user =
    await getUser(
      userId
    )

  if (user) {

    return user

  }

  /*
  |--------------------------------------------------------------------------
  | CREATE
  |--------------------------------------------------------------------------
  */

  user =
    await createUser(
      ctx
    )

  return user

}

/*
|--------------------------------------------------------------------------
| CHECK USER
|--------------------------------------------------------------------------
*/

const checkUser =
async (

  ctx,

  next

) => {

  /*
  |--------------------------------------------------------------------------
  | USER ID
  |--------------------------------------------------------------------------
  */

  const userId =
    getUserId(ctx)

  /*
  |--------------------------------------------------------------------------
  | INVALID
  |--------------------------------------------------------------------------
  */

  if (!userId) {

    return replyError(

      ctx,

      'Utilisateur invalide'

    )

  }

  /*
  |--------------------------------------------------------------------------
  | REGISTER
  |--------------------------------------------------------------------------
  */

  await registerUser(
    ctx
  )

  /*
  |--------------------------------------------------------------------------
  | NEXT
  |--------------------------------------------------------------------------
  */

  return next()

}

module.exports = {

  registerUser,

  checkUser

}