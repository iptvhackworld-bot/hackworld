const fs =
require('fs')

const path =
require('path')

/*
|--------------------------------------------------------------------------
| SHOW LOGS
|--------------------------------------------------------------------------
*/

const showLogs =
async (ctx) => {

  const logsPath =
    path.join(

      __dirname,

      '../data/logs.json'

    )

  /*
  |--------------------------------------------------------------------------
  | EXISTS
  |--------------------------------------------------------------------------
  */

  if (

    !fs.existsSync(
      logsPath
    )

  ) {

    return ctx.reply(
`
📜 Aucun log disponible.
`
    )

  }

  /*
  |--------------------------------------------------------------------------
  | READ
  |--------------------------------------------------------------------------
  */

  const logs =
    JSON.parse(

      fs.readFileSync(
        logsPath
      )

    )

  /*
  |--------------------------------------------------------------------------
  | EMPTY
  |--------------------------------------------------------------------------
  */

  if (
    logs.length === 0
  ) {

    return ctx.reply(
`
📜 Aucun log enregistré.
`
    )

  }

  /*
  |--------------------------------------------------------------------------
  | FORMAT
  |--------------------------------------------------------------------------
  */

  const lastLogs =
    logs
    .slice(-10)
    .reverse()

  let message =
`
📜 DERNIERS LOGS

━━━━━━━━━━━━━━━━━━

`

  lastLogs.forEach(
    (log) => {

      message +=
`
• ${log}

`
    }
  )

  /*
  |--------------------------------------------------------------------------
  | SEND
  |--------------------------------------------------------------------------
  */

  await ctx.reply(message)

}

module.exports = {

  showLogs

}