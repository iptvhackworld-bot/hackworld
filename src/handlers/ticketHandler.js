const env =
require(
  '../config/env'
)

const {

  logError

} = require(
  '../services/loggerService'
)

/*
|--------------------------------------------------------------------------
| OPEN SUPPORT
|--------------------------------------------------------------------------
*/

const openSupport =
async (ctx) => {

  /*
  |--------------------------------------------------------------------------
  | SESSION
  |--------------------------------------------------------------------------
  */

  if (!ctx.session) {

    ctx.session = {}

  }

  /*
  |--------------------------------------------------------------------------
  | STEP
  |--------------------------------------------------------------------------
  */

  ctx.session.step =
    'support_ticket'

  /*
  |--------------------------------------------------------------------------
  | MESSAGE
  |--------------------------------------------------------------------------
  */

  await ctx.reply(
`
🎫 SUPPORT PANEL

━━━━━━━━━━━━━━━━━━

📝 Envoyez votre problème.
`
  )

}

/*
|--------------------------------------------------------------------------
| HANDLE TICKET
|--------------------------------------------------------------------------
*/

const handleTicket =
async (ctx) => {

  /*
  |--------------------------------------------------------------------------
  | CHECK STEP
  |--------------------------------------------------------------------------
  */

  if (

    ctx.session.step !==
    'support_ticket'

  ) {

    return

  }

  const text =
    ctx.message.text

  /*
  |--------------------------------------------------------------------------
  | RESET STEP
  |--------------------------------------------------------------------------
  */

  ctx.session.step =
    null

  /*
  |--------------------------------------------------------------------------
  | SEND TO OWNER
  |--------------------------------------------------------------------------
  */

  try {

    await ctx.telegram.sendMessage(

      env.ownerId,

`
🎫 NOUVEAU TICKET

👤 @${ctx.from.username}

🆔 ${ctx.from.id}

📩 Message :

${text}
`

    )

  }

  catch (error) {

    logError(
      'Erreur ticket support',
      error
    )

  }

  /*
  |--------------------------------------------------------------------------
  | CONFIRMATION
  |--------------------------------------------------------------------------
  */

  await ctx.reply(
`
✅ Ticket envoyé au support.
`
  )

}

module.exports = {

  openSupport,

  handleTicket

}