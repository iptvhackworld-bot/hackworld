const {

  addRating

} = require(
  '../services/statsService'
)

/*
|--------------------------------------------------------------------------
| RATE BOT
|--------------------------------------------------------------------------
*/

const rateBot =
async (
  ctx,
  rating
) => {

  /*
  |--------------------------------------------------------------------------
  | SAVE RATING
  |--------------------------------------------------------------------------
  */

  addRating(rating)

  /*
  |--------------------------------------------------------------------------
  | ANSWER
  |--------------------------------------------------------------------------
  */

  await ctx.answerCbQuery(
    `⭐ Merci pour votre note ${rating}/5`
  )

  /*
  |--------------------------------------------------------------------------
  | MESSAGE
  |--------------------------------------------------------------------------
  */

  await ctx.reply(
`
⭐ Merci d’avoir noté le bot !

Votre note :

${'⭐'.repeat(rating)}

━━━━━━━━━━━━━━━━━━
`
  )

}

module.exports = {

  rateBot

}