const User =
require(
  '../models/User'
)

/*
|--------------------------------------------------------------------------
| PRESTIGE
|--------------------------------------------------------------------------
*/

const prestigeAccount =
async (ctx) => {

  const user =
    await User.findOne({

      id: ctx.from.id

    })

  if (!user) {

    return

  }

  /*
  |--------------------------------------------------------------------------
  | REQUIREMENT
  |--------------------------------------------------------------------------
  */

  if (

    user.level < 100

  ) {

    return ctx.reply(
`
❌ Niveau 100 requis.
`
    )

  }

  /*
  |--------------------------------------------------------------------------
  | RESET
  |--------------------------------------------------------------------------
  */

  user.level = 1

  user.xp = 0

  user.prestige += 1

  /*
  |--------------------------------------------------------------------------
  | BONUS
  |--------------------------------------------------------------------------
  */

  user.money +=
    50000

  await user.save()

  /*
  |--------------------------------------------------------------------------
  | RESULT
  |--------------------------------------------------------------------------
  */

  await ctx.reply(
`
👑 PRESTIGE ACTIVÉ

━━━━━━━━━━━━━━━━━━

⭐ Prestige :
${user.prestige}

💰 Bonus :
50000$

━━━━━━━━━━━━━━━━━━

🔥 Progression reset
`
  )

}

module.exports = {

  prestigeAccount

}