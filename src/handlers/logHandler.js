const {

  getLogs

} = require(
  '../services/logService'
)

/*
|--------------------------------------------------------------------------
| SHOW LOGS
|--------------------------------------------------------------------------
*/

const showLogs =
async (ctx) => {

  const logs =
    await getLogs()

  /*
  |--------------------------------------------------------------------------
  | EMPTY
  |--------------------------------------------------------------------------
  */

  if (
    logs.length === 0
  ) {

    return ctx.reply(
`
❌ Aucun log.
`
    )

  }

  /*
  |--------------------------------------------------------------------------
  | MESSAGE
  |--------------------------------------------------------------------------
  */

  let message =
`
📜 LOGS

━━━━━━━━━━━━━━━━━━

`

  logs.slice(0, 20)
  .forEach(

    (log) => {

      message +=
`
📌 ${log.type}

📝 ${log.message}

━━━━━━━━━━━━━━━━━━
`
    }

  )

  await ctx.reply(
    message
  )

}

module.exports = {

  showLogs

}