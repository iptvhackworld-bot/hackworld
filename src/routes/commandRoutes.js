module.exports = (bot) => {

  /*
  |--------------------------------------------------------------------------
  | IMPORTS
  |--------------------------------------------------------------------------
  */

  const {

    startHandler

  } = require(
    '../handlers/startHandler'
  )

  const {

    showProfile

  } = require(
    '../handlers/profileHandler'
  )

  const {

    dailyReward

  } = require(
    '../handlers/dailyHandler'
  )

  const {

    openShop

  } = require(
    '../handlers/shopHandler'
  )

  /*
  |--------------------------------------------------------------------------
  | START
  |--------------------------------------------------------------------------
  */

  bot.start(
    startHandler
  )

  /*
  |--------------------------------------------------------------------------
  | PROFILE
  |--------------------------------------------------------------------------
  */

  bot.command(

    'profile',

    showProfile

  )

  /*
  |--------------------------------------------------------------------------
  | DAILY
  |--------------------------------------------------------------------------
  */

  bot.command(

    'daily',

    dailyReward

  )

  /*
  |--------------------------------------------------------------------------
  | SHOP
  |--------------------------------------------------------------------------
  */

  bot.command(

    'shop',

    openShop

  )

}