module.exports = (bot) => {

  /*
  |--------------------------------------------------------------------------
  | IMPORTS
  |--------------------------------------------------------------------------
  */

  const {

    startHandler

  } = require(
    '../handlers/startHandler'
  )

  const {

  openProfile

} = require(
  '../handlers/profileHandler'
)

  const {

  claimDaily

} = require(
  '../handlers/dailyHandler'
)

  const {

    openShop

  } = require(
    '../handlers/shopHandler'
  )

  /*
  |--------------------------------------------------------------------------
  | START
  |--------------------------------------------------------------------------
  */

  bot.start(
    startHandler
  )

  /*
  |--------------------------------------------------------------------------
  | PROFILE
  |--------------------------------------------------------------------------
  */

  bot.command(

  'profile',

  openProfile

)

  /*
  |--------------------------------------------------------------------------
  | DAILY
  |--------------------------------------------------------------------------
  */

  bot.command(

  'daily',

  claimDaily

)

  /*
  |--------------------------------------------------------------------------
  | SHOP
  |--------------------------------------------------------------------------
  */

  bot.command(

    'shop',

    openShop

  )

}