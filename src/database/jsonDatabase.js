const fs = require('fs')

const cache =
require(
  '../cache/cacheManager'
)

/*
|--------------------------------------------------------------------------
| READ
|--------------------------------------------------------------------------
*/

const read = (
  filePath
) => {

  /*
  |--------------------------------------------------------------------------
  | CACHE
  |--------------------------------------------------------------------------
  */

  const cached =
    cache.get(filePath)

  if (cached) {

    return cached

  }

  /*
  |--------------------------------------------------------------------------
  | CREATE FILE
  |--------------------------------------------------------------------------
  */

  if (
    !fs.existsSync(filePath)
  ) {

    fs.writeFileSync(

      filePath,

      JSON.stringify(
        [],
        null,
        2
      )

    )

  }

  /*
  |--------------------------------------------------------------------------
  | READ FILE
  |--------------------------------------------------------------------------
  */

  const data =
    fs.readFileSync(
      filePath,
      'utf8'
    )

  /*
  |--------------------------------------------------------------------------
  | PARSE
  |--------------------------------------------------------------------------
  */

  const parsed =
    JSON.parse(data)

  /*
  |--------------------------------------------------------------------------
  | CACHE SAVE
  |--------------------------------------------------------------------------
  */

  cache.set(
    filePath,
    parsed
  )

  return parsed

}

/*
|--------------------------------------------------------------------------
| WRITE
|--------------------------------------------------------------------------
*/

const write = (
  filePath,
  data
) => {

  /*
  |--------------------------------------------------------------------------
  | CACHE UPDATE
  |--------------------------------------------------------------------------
  */

  cache.set(
    filePath,
    data
  )

  /*
  |--------------------------------------------------------------------------
  | WRITE FILE
  |--------------------------------------------------------------------------
  */

  fs.writeFileSync(

    filePath,

    JSON.stringify(
      data,
      null,
      2
    )

  )

}

module.exports = {

  read,

  write

}