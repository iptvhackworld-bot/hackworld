const mongoose =
require('mongoose')

const ticketSchema =
new mongoose.Schema({

  /*
  |--------------------------------------------------------------------------
  | USER
  |--------------------------------------------------------------------------
  */

  userId: {

    type: Number,

    required: true

  },

  username: {

    type: String,

    default: 'unknown'

  },

  /*
  |--------------------------------------------------------------------------
  | TICKET
  |--------------------------------------------------------------------------
  */

  subject: {

    type: String,

    default: ''

  },

  message: {

    type: String,

    default: ''

  },

  /*
  |--------------------------------------------------------------------------
  | STATUS
  |--------------------------------------------------------------------------
  */

  status: {

    type: String,

    default: 'open'

  },

  /*
  |--------------------------------------------------------------------------
  | STAFF
  |--------------------------------------------------------------------------
  */

  handledBy: {

    type: Number,

    default: 0

  },
  
  /*
|--------------------------------------------------------------------------
| REPLIES
|--------------------------------------------------------------------------
*/

replies: [

  {

    authorId: Number,

    authorUsername: String,

    message: String,

    createdAt: {

      type: Date,

      default: Date.now

    }

  }

],

  /*
  |--------------------------------------------------------------------------
  | DATE
  |--------------------------------------------------------------------------
  */

  createdAt: {

    type: Date,

    default: Date.now

  }

})

module.exports =
mongoose.model(

  'Ticket',

  ticketSchema

)