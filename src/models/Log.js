const mongoose =
require('mongoose')

const logSchema =
new mongoose.Schema({

  /*
  |--------------------------------------------------------------------------
  | TYPE
  |--------------------------------------------------------------------------
  */

  type: {

    type: String,

    required: true

  },

  /*
  |--------------------------------------------------------------------------
  | ADMIN
  |--------------------------------------------------------------------------
  */

  adminId: {

    type: Number,

    required: true

  },

  adminUsername: {

    type: String,

    default: 'Unknown'

  },

  /*
  |--------------------------------------------------------------------------
  | TARGET
  |--------------------------------------------------------------------------
  */

  targetId: {

    type: Number,

    required: true

  },

  targetUsername: {

    type: String,

    default: 'Unknown'

  },

  /*
  |--------------------------------------------------------------------------
  | DATA
  |--------------------------------------------------------------------------
  */

  reason: {

    type: String,

    default: 'Aucune raison'

  },

  /*
  |--------------------------------------------------------------------------
  | DATE
  |--------------------------------------------------------------------------
  */

  createdAt: {

    type: Date,

    default: Date.now

  }

})

module.exports =
mongoose.model(

  'Log',

  logSchema

)