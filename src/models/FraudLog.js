const mongoose =
require('mongoose')

const fraudLogSchema =
new mongoose.Schema({

  /*
  |--------------------------------------------------------------------------
  | USER
  |--------------------------------------------------------------------------
  */

  userId: {

    type: Number,

    required: true

  },

  /*
  |--------------------------------------------------------------------------
  | TYPE
  |--------------------------------------------------------------------------
  */

  type: {

    type: String,

    required: true

  },

  /*
  |--------------------------------------------------------------------------
  | REASON
  |--------------------------------------------------------------------------
  */

  reason: {

    type: String,

    required: true

  },

  /*
  |--------------------------------------------------------------------------
  | RISK SCORE
  |--------------------------------------------------------------------------
  */

  risk: {

    type: Number,

    default: 0

  },

  /*
  |--------------------------------------------------------------------------
  | DATES
  |--------------------------------------------------------------------------
  */

  createdAt: {

    type: Date,

    default: Date.now

  }

})

module.exports =
mongoose.model(

  'FraudLog',

  fraudLogSchema

)