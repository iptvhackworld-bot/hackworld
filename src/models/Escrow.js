const mongoose =
require('mongoose')

const escrowSchema =
new mongoose.Schema({

  /*
  |--------------------------------------------------------------------------
  | USERS
  |--------------------------------------------------------------------------
  */

  buyerId: {

    type: Number,

    required: true

  },

  sellerId: {

    type: Number,

    required: true

  },

  /*
  |--------------------------------------------------------------------------
  | MONEY
  |--------------------------------------------------------------------------
  */

  amount: {

    type: Number,

    required: true

  },

  /*
  |--------------------------------------------------------------------------
  | ITEM
  |--------------------------------------------------------------------------
  */

  itemTitle: {

    type: String,

    default: ''

  },

  /*
  |--------------------------------------------------------------------------
  | STATUS
  |--------------------------------------------------------------------------
  */

  status: {

    type: String,

    default: 'pending'

  },

  /*
  |--------------------------------------------------------------------------
  | CONFIRMATIONS
  |--------------------------------------------------------------------------
  */

  buyerConfirmed: {

    type: Boolean,

    default: false

  },

  sellerConfirmed: {

    type: Boolean,

    default: false

  },

  /*
  |--------------------------------------------------------------------------
  | DISPUTE
  |--------------------------------------------------------------------------
  */

  disputed: {

    type: Boolean,

    default: false

  },

  /*
  |--------------------------------------------------------------------------
  | DATE
  |--------------------------------------------------------------------------
  */

  createdAt: {

    type: Date,

    default: Date.now

  }

})

module.exports =
mongoose.model(

  'Escrow',

  escrowSchema

)