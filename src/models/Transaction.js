const mongoose =
require('mongoose')

const transactionSchema =
new mongoose.Schema({

  /*
  |--------------------------------------------------------------------------
  | USERS
  |--------------------------------------------------------------------------
  */

  userId: {

    type: Number,

    required: true

  },

  /*
  |--------------------------------------------------------------------------
  | TYPE
  |--------------------------------------------------------------------------
  */

  type: {

    type: String,

    required: true

  },

  /*
  |--------------------------------------------------------------------------
  | MONEY
  |--------------------------------------------------------------------------
  */

  amount: {

    type: Number,

    required: true

  },

  /*
  |--------------------------------------------------------------------------
  | DESCRIPTION
  |--------------------------------------------------------------------------
  */

  description: {

    type: String,

    default: 'Aucune'

  },

  /*
  |--------------------------------------------------------------------------
  | DATE
  |--------------------------------------------------------------------------
  */

  createdAt: {

    type: Date,

    default: Date.now

  }

})

module.exports =
mongoose.model(

  'Transaction',

  transactionSchema

)