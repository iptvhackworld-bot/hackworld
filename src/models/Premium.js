const mongoose =
require('mongoose')

const premiumSchema =
new mongoose.Schema({

  /*
  |--------------------------------------------------------------------------
  | USER
  |--------------------------------------------------------------------------
  */

  userId: {

    type: Number,

    unique: true,

    required: true

  },

  /*
  |--------------------------------------------------------------------------
  | TYPE
  |--------------------------------------------------------------------------
  */

  plan: {

    type: String,

    default: 'gold'

  },

  /*
  |--------------------------------------------------------------------------
  | EXPIRATION
  |--------------------------------------------------------------------------
  */

  expiresAt: {

    type: Date,

    required: true

  },

  /*
  |--------------------------------------------------------------------------
  | DATE
  |--------------------------------------------------------------------------
  */

  createdAt: {

    type: Date,

    default: Date.now

  }

})

module.exports =
mongoose.model(

  'Premium',

  premiumSchema

)