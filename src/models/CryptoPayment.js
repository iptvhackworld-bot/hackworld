const mongoose =
require('mongoose')

const paymentSchema =
new mongoose.Schema({

  /*
  |--------------------------------------------------------------------------
  | USER
  |--------------------------------------------------------------------------
  */

  userId: {

    type: Number,

    required: true

  },

  username: {

    type: String,

    default: ''

  },

  /*
  |--------------------------------------------------------------------------
  | PLAN
  |--------------------------------------------------------------------------
  */

  plan: {

    type: String,

    default: 'premium'

  },

  amount: {

    type: Number,

    default: 0

  },

  currency: {

    type: String,

    default: 'USDT'

  },

  /*
  |--------------------------------------------------------------------------
  | PROOF
  |--------------------------------------------------------------------------
  */

  proofFileId: {

    type: String,

    default: ''

  },

  /*
  |--------------------------------------------------------------------------
  | STATUS
  |--------------------------------------------------------------------------
  */

  status: {

    type: String,

    default: 'pending'

  },

  /*
  |--------------------------------------------------------------------------
  | DATE
  |--------------------------------------------------------------------------
  */

  createdAt: {

    type: Date,

    default: Date.now

  }

})

module.exports =
mongoose.model(

  'CryptoPayment',

  paymentSchema

)