const mongoose =
require('mongoose')

const userSchema =
new mongoose.Schema({

  /*
  |--------------------------------------------------------------------------
  | TELEGRAM
  |--------------------------------------------------------------------------
  */

  id: {

    type: Number,

    unique: true

  },

  username: {

    type: String

  },

  firstName: {

    type: String

  },

  /*
  |--------------------------------------------------------------------------
  | ECONOMY
  |--------------------------------------------------------------------------
  */

  money: {

    type: Number,

    default: 0

  },

  xp: {

    type: Number,

    default: 0

  },

  /*
  |--------------------------------------------------------------------------
  | CASINO
  |--------------------------------------------------------------------------
  */

  casinoPlayed: {

    type: Number,

    default: 0

  },

  casinoWon: {

    type: Number,

    default: 0

  },

  /*
  |--------------------------------------------------------------------------
  | ADMIN
  |--------------------------------------------------------------------------
  */

  role: {

    type: String,

    default: 'user'

  },

  banned: {

    type: Boolean,

    default: false

  },

  warns: {

    type: Number,

    default: 0

  },

  /*
  |--------------------------------------------------------------------------
  | STATS
  |--------------------------------------------------------------------------
  */

  messages: {

    type: Number,

    default: 0

  },

  rating: {

    type: Number,

    default: 0

  },

  /*
  |--------------------------------------------------------------------------
  | DATES
  |--------------------------------------------------------------------------
  */

  createdAt: {

    type: Date,

    default: Date.now

  }

})

module.exports =
mongoose.model(

  'User',

  userSchema

)