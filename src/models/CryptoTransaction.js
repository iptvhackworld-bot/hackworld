const mongoose =
require('mongoose')

const cryptoTransactionSchema =
new mongoose.Schema({

  /*
  |--------------------------------------------------------------------------
  | USER
  |--------------------------------------------------------------------------
  */

  userId: {

    type: Number,

    required: true

  },

  /*
  |--------------------------------------------------------------------------
  | TYPE
  |--------------------------------------------------------------------------
  */

  type: {

    type: String,

    required: true

  },

  /*
  |--------------------------------------------------------------------------
  | COIN
  |--------------------------------------------------------------------------
  */

  coin: {

    type: String,

    required: true

  },

  /*
  |--------------------------------------------------------------------------
  | AMOUNT
  |--------------------------------------------------------------------------
  */

  amount: {

    type: Number,

    required: true

  },

  /*
  |--------------------------------------------------------------------------
  | STATUS
  |--------------------------------------------------------------------------
  */

  status: {

    type: String,

    default: 'completed'

  },

  /*
  |--------------------------------------------------------------------------
  | HASH
  |--------------------------------------------------------------------------
  */

  txHash: {

    type: String,

    default: null

  },

  /*
  |--------------------------------------------------------------------------
  | DATES
  |--------------------------------------------------------------------------
  */

  createdAt: {

    type: Date,

    default: Date.now

  }

})

module.exports =
mongoose.model(

  'CryptoTransaction',

  cryptoTransactionSchema

)