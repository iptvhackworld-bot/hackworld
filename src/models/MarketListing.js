const mongoose =
require('mongoose')

const marketListingSchema =
new mongoose.Schema({

  /*
  |--------------------------------------------------------------------------
  | SELLER
  |--------------------------------------------------------------------------
  */

  sellerId: {

    type: Number,

    required: true

  },

  sellerUsername: {

    type: String,

    default: 'unknown'

  },

  /*
  |--------------------------------------------------------------------------
  | ITEM
  |--------------------------------------------------------------------------
  */

  title: {

    type: String,

    required: true

  },

  description: {

    type: String,

    default: 'Aucune'

  },

  /*
  |--------------------------------------------------------------------------
  | PRICE
  |--------------------------------------------------------------------------
  */

  price: {

    type: Number,

    required: true

  },

  /*
  |--------------------------------------------------------------------------
  | STATUS
  |--------------------------------------------------------------------------
  */

  sold: {

    type: Boolean,

    default: false

  },

  /*
  |--------------------------------------------------------------------------
  | STATS
  |--------------------------------------------------------------------------
  */

  views: {

    type: Number,

    default: 0

  },

  /*
  |--------------------------------------------------------------------------
  | DATE
  |--------------------------------------------------------------------------
  */

  createdAt: {

    type: Date,

    default: Date.now

  }

})

module.exports =
mongoose.model(

  'MarketListing',

  marketListingSchema

)