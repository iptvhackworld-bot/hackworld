const mongoose =
require('mongoose')

const marketListingSchema =
new mongoose.Schema({

  /*
  |--------------------------------------------------------------------------
  | SELLER
  |--------------------------------------------------------------------------
  */

  sellerId: {

    type: Number,

    required: true

  },

  sellerUsername: {

    type: String,

    default: 'unknown'

  },

  /*
  |--------------------------------------------------------------------------
  | ITEM
  |--------------------------------------------------------------------------
  */

  title: {

    type: String,

    required: true

  },
  
  /*
|--------------------------------------------------------------------------
| REVIEWS
|--------------------------------------------------------------------------
*/

averageRating: {

  type: Number,

  default: 0

},

reviewCount: {

  type: Number,

  default: 0

},

/*
|--------------------------------------------------------------------------
| FEATURED
|--------------------------------------------------------------------------
*/

featured: {

  type: Boolean,

  default: false

},

featuredExpiresAt: {

  type: Date,

  default: null

},

/*
|--------------------------------------------------------------------------
| IMAGE
|--------------------------------------------------------------------------
*/

imageUrl: {

  type: String,

  default: ''

},
  
  /*
|--------------------------------------------------------------------------
| CATEGORY
|--------------------------------------------------------------------------
*/

category: {

  type: String,

  default: 'Other'

},

  description: {

    type: String,

    default: 'Aucune'

  },

  /*
  |--------------------------------------------------------------------------
  | PRICE
  |--------------------------------------------------------------------------
  */

  price: {

    type: Number,

    required: true

  },

  /*
  |--------------------------------------------------------------------------
  | STATUS
  |--------------------------------------------------------------------------
  */

  sold: {

    type: Boolean,

    default: false

  },

  /*
  |--------------------------------------------------------------------------
  | STATS
  |--------------------------------------------------------------------------
  */

  views: {

    type: Number,

    default: 0

  },

  /*
  |--------------------------------------------------------------------------
  | FEATURED
  |--------------------------------------------------------------------------
  */

  featured: {

    type: Boolean,

    default: false

  },

  featuredExpiresAt: {

    type: Date,

    default: null

  },

  /*
  |--------------------------------------------------------------------------
  | DATE
  |--------------------------------------------------------------------------
  */

  createdAt: {

    type: Date,

    default: Date.now

  }

})

module.exports =
mongoose.model(

  'MarketListing',

  marketListingSchema

)