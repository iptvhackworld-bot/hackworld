const mongoose =
require('mongoose')

const disputeSchema =
new mongoose.Schema({

  /*
  |--------------------------------------------------------------------------
  | PURCHASE
  |--------------------------------------------------------------------------
  */

  purchaseId: {

    type: mongoose.Schema.Types.ObjectId,

    required: true

  },

  /*
  |--------------------------------------------------------------------------
  | USERS
  |--------------------------------------------------------------------------
  */

  buyerId: {

    type: Number,

    required: true

  },

  sellerId: {

    type: Number,

    required: true

  },

  /*
  |--------------------------------------------------------------------------
  | REASON
  |--------------------------------------------------------------------------
  */

  reason: {

    type: String,

    default: ''

  },

  /*
  |--------------------------------------------------------------------------
  | STATUS
  |--------------------------------------------------------------------------
  */

  status: {

    type: String,

    default: 'open'

  },

  /*
  |--------------------------------------------------------------------------
  | DATE
  |--------------------------------------------------------------------------
  */

  createdAt: {

    type: Date,

    default: Date.now

  }

})

module.exports =
mongoose.model(

  'Dispute',

  disputeSchema

)