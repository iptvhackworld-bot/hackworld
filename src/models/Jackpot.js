const mongoose =
require('mongoose')

const jackpotSchema =
new mongoose.Schema({

  /*
  |--------------------------------------------------------------------------
  | POT
  |--------------------------------------------------------------------------
  */

  amount: {

    type: Number,

    default: 0

  },

  /*
  |--------------------------------------------------------------------------
  | PLAYERS
  |--------------------------------------------------------------------------
  */

  players: [

    {

      userId: Number,

      username: String,

      tickets: Number

    }

  ],

  /*
  |--------------------------------------------------------------------------
  | STATUS
  |--------------------------------------------------------------------------
  */

  active: {

    type: Boolean,

    default: true

  },

  /*
  |--------------------------------------------------------------------------
  | DATES
  |--------------------------------------------------------------------------
  */

  createdAt: {

    type: Date,

    default: Date.now

  }

})

module.exports =
mongoose.model(

  'Jackpot',

  jackpotSchema

)