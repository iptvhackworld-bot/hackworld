/*
|--------------------------------------------------------------------------
| USER ID
|--------------------------------------------------------------------------
*/

const getUserId = (
  ctx
) => {

  return ctx.from?.id

}

/*
|--------------------------------------------------------------------------
| USERNAME
|--------------------------------------------------------------------------
*/

const getUsername = (
  ctx
) => {

  return (
    ctx.from?.username ||
    'unknown'
  )

}

/*
|--------------------------------------------------------------------------
| MESSAGE
|--------------------------------------------------------------------------
*/

const getMessageText = (
  ctx
) => {

  return (
    ctx.message?.text ||
    ''
  )

}

/*
|--------------------------------------------------------------------------
| SESSION
|--------------------------------------------------------------------------
*/

const getSession = (
  ctx
) => {

  if (!ctx.session) {

    ctx.session = {}

  }

  return ctx.session

}

/*
|--------------------------------------------------------------------------
| RESET SESSION
|--------------------------------------------------------------------------
*/

const resetSession = (
  ctx
) => {

  ctx.session = {}

}

module.exports = {

  getUserId,

  getUsername,

  getMessageText,

  getSession,

  resetSession

}