const {

  loadStats,

  saveStats

} = require(
  '../data/statsData'
)

const {

  loadUsers

} = require(
  '../data/userData'
)

/*
|--------------------------------------------------------------------------
| GET TOTAL USERS
|--------------------------------------------------------------------------
*/

const getTotalUsers =
() => {

  const users =
    loadUsers()

  return users.length

}

/*
|--------------------------------------------------------------------------
| GET TOTAL USES
|--------------------------------------------------------------------------
*/

const getTotalUses =
() => {

  const stats =
    loadStats()

  /*
  |--------------------------------------------------------------------------
  | FIX EMPTY
  |--------------------------------------------------------------------------
  */

  if (
    typeof stats.uses !==
    'number'
  ) {

    stats.uses = 0

    saveStats(stats)

  }

  return stats.uses

}

/*
|--------------------------------------------------------------------------
| INCREMENT USES
|--------------------------------------------------------------------------
*/

const incrementUses =
() => {

  const stats =
    loadStats()

  /*
  |--------------------------------------------------------------------------
  | FIX EMPTY
  |--------------------------------------------------------------------------
  */

  if (
    typeof stats.uses !==
    'number'
  ) {

    stats.uses = 0

  }

  stats.uses += 1

  saveStats(stats)

}

/*
|--------------------------------------------------------------------------
| ADD RATING
|--------------------------------------------------------------------------
*/

const addRating = (
  rating
) => {

  const stats =
    loadStats()

  /*
  |--------------------------------------------------------------------------
  | FIX EMPTY
  |--------------------------------------------------------------------------
  */

  if (

    !stats.ratings ||

    !Array.isArray(
      stats.ratings
    )

  ) {

    stats.ratings = []

  }

  /*
  |--------------------------------------------------------------------------
  | PUSH
  |--------------------------------------------------------------------------
  */

  stats.ratings.push(
    rating
  )

  /*
  |--------------------------------------------------------------------------
  | SAVE
  |--------------------------------------------------------------------------
  */

  saveStats(stats)

}

/*
|--------------------------------------------------------------------------
| GET AVERAGE RATING
|--------------------------------------------------------------------------
*/

const getAverageRating =
() => {

  const stats =
    loadStats()

  /*
  |--------------------------------------------------------------------------
  | FIX EMPTY
  |--------------------------------------------------------------------------
  */

  if (

    !stats.ratings ||

    !Array.isArray(
      stats.ratings
    )

  ) {

    stats.ratings = []

    saveStats(stats)

  }

  /*
  |--------------------------------------------------------------------------
  | EMPTY
  |--------------------------------------------------------------------------
  */

  if (
    stats.ratings.length === 0
  ) {

    return '0.0'

  }

  /*
  |--------------------------------------------------------------------------
  | CALCULATE
  |--------------------------------------------------------------------------
  */

  const total =
    stats.ratings.reduce(

      (sum, rating) =>

        sum + rating,

      0

    )

  return (
    total /
    stats.ratings.length
  ).toFixed(1)

}

module.exports = {

  getTotalUsers,

  getTotalUses,

  incrementUses,

  addRating,

  getAverageRating

}