const User =
require(
  '../models/User'
)

/*
|--------------------------------------------------------------------------
| TOTAL USERS
|--------------------------------------------------------------------------
*/

const getTotalUsers =
async () => {

  return await User.countDocuments()

}

/*
|--------------------------------------------------------------------------
| TOTAL USES
|--------------------------------------------------------------------------
*/

let totalUses = 0

const incrementUses =
() => {

  totalUses++

}

const getTotalUses =
() => {

  return totalUses

}

/*
|--------------------------------------------------------------------------
| AVERAGE RATING
|--------------------------------------------------------------------------
*/

const getAverageRating =
async () => {

  const users =
    await User.find({

      rating: {

        $gt: 0

      }

    })

  /*
  |--------------------------------------------------------------------------
  | EMPTY
  |--------------------------------------------------------------------------
  */

  if (
    users.length === 0
  ) {

    return 0

  }

  /*
  |--------------------------------------------------------------------------
  | TOTAL
  |--------------------------------------------------------------------------
  */

  const total =
    users.reduce(

      (
        sum,
        user
      ) =>

        sum +
        user.rating,

      0

    )

  /*
  |--------------------------------------------------------------------------
  | AVERAGE
  |--------------------------------------------------------------------------
  */

  return (
    total /
    users.length
  ).toFixed(1)

}

module.exports = {

  getTotalUsers,

  incrementUses,

  getTotalUses,

  getAverageRating

}