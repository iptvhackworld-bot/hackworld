const User =
require(
  '../models/User'
)

const CasinoHistory =
require(
  '../models/CasinoHistory'
)

/*
|--------------------------------------------------------------------------
| PLAY ROULETTE
|--------------------------------------------------------------------------
*/

const playRoulette =
async (

  userId,

  amount

) => {

  const user =
    await User.findOne({

      id: userId

    })

  /*
  |--------------------------------------------------------------------------
  | USER
  |--------------------------------------------------------------------------
  */

  if (!user) {

    return {

      error:
      'Utilisateur introuvable'

    }

  }

  /*
  |--------------------------------------------------------------------------
  | MONEY
  |--------------------------------------------------------------------------
  */

  if (
    user.money < amount
  ) {

    return {

      error:
      'Argent insuffisant'

    }

  }

  /*
  |--------------------------------------------------------------------------
  | GAME
  |--------------------------------------------------------------------------
  */

  const win =
    Math.random() < 0.5

  let profit = 0

  if (win) {

    profit = amount

    user.money += amount

    user.casinoWon += amount

  }

  else {

    profit = -amount

    user.money -= amount

  }

  /*
  |--------------------------------------------------------------------------
  | STATS
  |--------------------------------------------------------------------------
  */

  user.casinoPlayed += 1

  /*
  |--------------------------------------------------------------------------
  | SAVE USER
  |--------------------------------------------------------------------------
  */

  await user.save()

  /*
  |--------------------------------------------------------------------------
  | HISTORY
  |--------------------------------------------------------------------------
  */

  await CasinoHistory.create({

    userId,

    game: 'roulette',

    amount,

    result:
      win
      ?
      'win'
      :
      'lose',

    profit

  })

  /*
  |--------------------------------------------------------------------------
  | RETURN
  |--------------------------------------------------------------------------
  */

  return {

    win,

    profit,

    money:
      user.money

  }

}

module.exports = {

  playRoulette

}